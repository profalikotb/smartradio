export function fmt(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** dd/MM/yyyy and 12-hour time, Latin digits for consistency across both languages. */
export function fmtDate(ts: number | string | undefined): string {
  if (!ts) return "—";
  const d = new Date(ts);
  if (isNaN(d.getTime())) return "—";
  const p = (n: number) => String(n).padStart(2, "0");
  return `${p(d.getDate())}/${p(d.getMonth() + 1)}/${d.getFullYear()}`;
}

export function fmtTime(ts: number, lang: Lang): string {
  const d = new Date(ts);
  let h = d.getHours();
  const m = String(d.getMinutes()).padStart(2, "0");
  const am = h < 12;
  h = h % 12 || 12;
  return `${h}:${m} ${lang === "ar" ? (am ? "ص" : "م") : am ? "AM" : "PM"}`;
}

export function fmtDateTime(ts: number | undefined, lang: Lang): string {
  return ts ? `${fmtDate(ts)} ${fmtTime(ts, lang)}` : "—";
}
